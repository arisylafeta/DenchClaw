-- The model text as the alias list reads it: lower case, accents folded, kWh/kW/Ah figures, bracketed asides, years
-- (unless nothing else is left), battery/pack/module words and a leading make removed, trailing trim words dropped.
-- Mirrors normal_tokens() in model_aliases.py and normalModelText() in product-key-for.ts.
create or replace function buyer_interest_model_norm(p_make text, p_raw text) returns text language plpgsql stable as $$
declare
  drop_years boolean;
  t text;
  own text := btrim(regexp_replace(buyer_interest_unaccent(coalesce(p_make, '')), '[^a-z0-9]+', ' ', 'g'));
  brand text;
  toks text[];
begin
  foreach drop_years in array array[true, false] loop
    t := buyer_interest_unaccent(coalesce(p_raw, ''));
    t := regexp_replace(t, '\y[0-9]+(\.[0-9]+)?\s*(kwh|kw|ps|hp|bhp|ah)\y', ' ', 'g');
    t := regexp_replace(t, '\([^)]*\)|\[[^\]]*\]', ' ', 'g');
    if drop_years then t := regexp_replace(t, '\y(19|20)[0-9]{2}\y', ' ', 'g'); end if;
    t := regexp_replace(t, '\y(battery|batteries|packs?|modules?|hv|high voltage)\y', ' ', 'g');
    t := btrim(regexp_replace(t, '[^a-z0-9]+', ' ', 'g'));
    for brand in
      select b from (select distinct x as b from unnest(array[own,
        -- BEGIN GENERATED BRAND WORDS
        'volkswagen', 'vw', 'audi', 'mini', 'skoda', 'cupra', 'porsche', 'bmw', 'mercedes benz', 'mercedes', 'tesla', 'stellantis', 'nissan', 'renault', 'dacia', 'peugeot', 'citroen', 'opel', 'vauxhall', 'fiat', 'jeep', 'ford', 'hyundai', 'kia', 'genesis', 'toyota', 'lexus', 'honda', 'mazda', 'mitsubishi', 'suzuki', 'subaru', 'volvo', 'polestar', 'jaguar', 'land rover', 'mg', 'byd', 'lotus', 'lucid', 'rivian', 'nio', 'xpeng', 'zeekr', 'leapmotor', 'maxus', 'smart', 'seat'
        -- END GENERATED BRAND WORDS
        ]) x where x <> '') s
      order by length(b) desc, b
    loop
      if brand = 'smart' and own <> '' and own not in ('smart', 'mercedes', 'mercedes benz') then continue; end if;
      if left(t, length(brand) + 1) = brand || ' ' then
        t := substr(t, length(brand) + 2);
        exit;
      end if;
    end loop;
    toks := string_to_array(t, ' ');
    while cardinality(toks) > 1 and toks[cardinality(toks)] in (
      -- BEGIN GENERATED VARIANT WORDS
      'long', 'range', 'standard', 'awd', 'rwd', 'fwd', '4wd', '2wd', 'lr', 'sr', 'dual', 'motor', 'performance', 'premium', 'se'
      -- END GENERATED VARIANT WORDS
      ) loop
      toks := toks[1:cardinality(toks) - 1];
    end loop;
    t := array_to_string(toks, ' ');
    if t <> '' then return t; end if;
  end loop;
  return null;
end $$;

-- The canonical slug of a model text under a make when the alias list names it, else null. A text that lists models
-- (comma, semicolon, colon) names none. With a slash the whole text must equal an alias; otherwise it equals an alias or
-- starts with one followed by a space, longest first, and an alias of the line's own make wins. Mirrors alias matching in
-- model_slug() of model_aliases.py.
create or replace function buyer_interest_model_alias_slug(p_make text, p_raw text) returns text language plpgsql stable as $$
declare
  norm text;
  mk text := nullif(buyer_interest_alias_make_fold(p_make), '');
  exact_only boolean := position('/' in coalesce(p_raw, '')) > 0;
  found text;
begin
  if nullif(btrim(coalesce(p_raw, '')), '') is null or p_raw ~ '[,;:]' then return null; end if;
  norm := buyer_interest_model_norm(p_make, p_raw);
  if norm is null then return null; end if;
  select a.slug into found
  from buyer_interest_model_alias a
  where (norm = a.alias or (not exact_only and left(norm, length(a.alias) + 1) = a.alias || ' '))
    and (coalesce(a.own = mk, false) or a.is_global)
  order by coalesce(a.own = mk, false) desc, length(a.alias) desc, a.ord
  limit 1;
  return found;
end $$;

-- The model segment of a key: the canonical slug, else the folded text without a leading make (what the TypeScript
-- normalModel() drops: the make as written, its canonical name, or Mercedes-Benz with a space).
create or replace function buyer_interest_model_key(p_make text, p_text text) returns text language sql stable as $$
  select coalesce(buyer_interest_model_alias_slug(p_make, p_text), buyer_interest_fold(
    coalesce((select substr(p_text, length(prefix) + 2)
                from unnest(array[lower(btrim(coalesce(p_make, ''))), lower(btrim(coalesce(buyer_interest_make(p_make), ''))),
                  replace(lower(btrim(coalesce(buyer_interest_make(p_make), ''))), '-', ' ')]) prefix
               where prefix <> '' and lower(p_text) like prefix || ' %' and btrim(substr(p_text, length(prefix) + 2)) <> ''
               order by length(prefix) desc limit 1), p_text)))
$$;

-- What the source said that its key cannot hold: a prose model, a part number that is a product name, and a chemistry
-- list that was not paired with the makes or models (kept as a preference).
create or replace function buyer_interest_raw_product(facts jsonb) returns text language sql immutable as $$
  select nullif(concat_ws('; ',
    coalesce(
      case when buyer_interest_prose_model(facts->>'model') then btrim(facts->>'model') end,
      (select min(btrim(part)) from jsonb_array_elements_text(
         case when jsonb_typeof(facts->'part_numbers') = 'array' then facts->'part_numbers' else '[]'::jsonb end) part
        where buyer_interest_part(part) is null and nullif(btrim(part), '') is not null)),
    case when nullif(btrim(coalesce(facts->>'chemistry_preference', '')), '') is not null
      then 'chemistry preference: ' || btrim(facts->>'chemistry_preference') end), '')
$$;

-- ---------------------------------------------------------------------------------------------- models a text names
-- Models a free text names, longest alias first, each text span used once: one row per model and per kWh figure that
-- belongs to it (no kWh is one row with a null). A model owns the kWh groups after it, up to the next model
-- ("Zoe 22 kWh, Leaf 40 kWh" is Zoe 22 and Leaf 40); a model with none inherits the group of the model right after it
-- ("Kona, Niro 39 kWh" is both 39); a single model also takes a group written before it ("40 kWh Leaf"). A group lists
-- values: "22/41/52kWh", "22 or 41 kWh". An alias counts when its make is named (in the text or in p_makes) or when it
-- carries a digit and one model owns it (model 3, ev6). Mirrors text_models() of model_aliases.py, which has no kWh.
create or replace function buyer_interest_text_models(p_text text, p_makes text[] default '{}')
returns table (own text, make_display text, slug text, name text, kwh numeric) language plpgsql stable as $$
declare
  -- A kWh group: values joined by / , & or and, the last one followed by kWh. Earlier values have two or three digits
  -- (so "Model 3, 75 kWh" is Model 3 and 75).
  kwh_re constant text := '(?:(?:[0-9]{2,3}(?:\.[0-9]+)?|[0-9]\.[0-9]+)(?:\s*kwh)?\s*(?:/|,|&|\yor\y|\yand\y)\s*)*[0-9]+(?:\.[0-9]+)?\s*kwh';
  text_ text := regexp_replace(coalesce(p_text, ''), '[(\[]([^)\]]*[0-9]\s*kwh[^)\]]*)[)\]]', ' \1 ', 'gi');
  grp text[];
  grp_vals jsonb[] := '{}';
  grp_pos int[] := '{}';
  g int;
  words text;
  hints text[] := '{}';
  word text;
  piece text;
  r record;
  pos int;
  seen text[] := '{}';
  f_own text[] := '{}'; f_disp text[] := '{}'; f_slug text[] := '{}'; f_name text[] := '{}'; f_pos int[] := '{}'; f_len int[] := '{}';
  n int;
  ord int[];
  k int;
  idx int;
  next_pos int;
  mine jsonb[];
  assigned jsonb[];
  between_ text;
  v text;
begin
  -- Each kWh group becomes one placeholder word, so its place among the models is known.
  for grp in select regexp_matches(text_, '(' || kwh_re || ')', 'gi') loop
    grp_vals := grp_vals || coalesce((select jsonb_agg(distinct x::numeric) from unnest(regexp_split_to_array(
      regexp_replace(lower(grp[1]), '\s*kwh|\s+', '', 'g'), '/|,|&|or|and')) x where x ~ '^[0-9]+(\.[0-9]+)?$'), '[]'::jsonb);
  end loop;
  g := 0;
  words := text_;
  loop
    exit when g >= cardinality(grp_vals);
    g := g + 1;
    words := regexp_replace(words, kwh_re, ' zkwh' || g || 'z ', 'i');
  end loop;
  words := regexp_replace(words, '\([^)]*\)|\[[^\]]*\]', ' ', 'g');
  words := ' ' || btrim(regexp_replace(buyer_interest_unaccent(words), '[^a-z0-9]+', ' ', 'g')) || ' ';
  foreach word in array string_to_array(btrim(words), ' ') loop
    hints := hints || buyer_interest_alias_make_fold(word);
  end loop;
  foreach word in array coalesce(p_makes, '{}') loop
    foreach piece in array regexp_split_to_array(coalesce(word, ''), '\s*(,|/|&|\yand\y|\yor\y)\s*', 'i') loop
      hints := hints || buyer_interest_alias_make_fold(piece);
      if buyer_interest_make(piece) = 'vw-group' then hints := hints || array['volkswagen', 'audi', 'skoda', 'seat', 'cupra', 'porsche']; end if;
    end loop;
  end loop;
  for r in select * from buyer_interest_model_alias a order by length(a.alias_spaced) desc, a.ord loop
    if not (r.own = any(hints) or r.alone) then continue; end if;
    pos := position(' ' || r.alias_spaced || ' ' in words);
    if pos = 0 then continue; end if;
    words := overlay(words placing repeat(' ', length(r.alias_spaced)) from pos + 1 for length(r.alias_spaced));
    if (r.own || '/' || r.slug) = any(seen) then continue; end if;
    seen := seen || (r.own || '/' || r.slug);
    f_own := f_own || r.own; f_disp := f_disp || r.make_display; f_slug := f_slug || r.slug; f_name := f_name || r.name;
    f_pos := f_pos || (pos + 1); f_len := f_len || length(r.alias_spaced);
  end loop;

  n := cardinality(f_pos);
  if n = 0 then return; end if;
  for g in 1..cardinality(grp_vals) loop
    grp_pos := grp_pos || position(' zkwh' || g || 'z ' in words);
  end loop;
  ord := array(select i from generate_subscripts(f_pos, 1) i order by f_pos[i]);
  assigned := array_fill('[]'::jsonb, array[n]);
  for k in reverse n..1 loop
    idx := ord[k];
    next_pos := case when k < n then f_pos[ord[k + 1]] else length(words) + 2 end;
    mine := '{}';
    for g in 1..cardinality(grp_vals) loop
      if grp_pos[g] >= f_pos[idx] + f_len[idx] and grp_pos[g] < next_pos then mine := mine || grp_vals[g]; end if;
    end loop;
    if cardinality(mine) = 0 and k < n then
      between_ := substr(words, f_pos[idx] + f_len[idx], next_pos - f_pos[idx] - f_len[idx]);
      if between_ ~ '^\s*((and|or)\s*)?$' then assigned[idx] := assigned[ord[k + 1]]; end if;
    end if;
    if cardinality(mine) = 0 and k = 1 and n = 1 then
      for g in 1..cardinality(grp_vals) loop mine := mine || grp_vals[g]; end loop;
    end if;
    if cardinality(mine) > 0 then
      assigned[idx] := (select jsonb_agg(distinct x::numeric) from unnest(mine) m, jsonb_array_elements_text(m) x);
    end if;
  end loop;

  for k in 1..n loop
    idx := ord[k];
    own := f_own[idx]; make_display := f_disp[idx]; slug := f_slug[idx]; name := f_name[idx];
    if jsonb_array_length(assigned[idx]) = 0 then
      kwh := null;
      return next;
    else
      for v in select x from jsonb_array_elements_text(assigned[idx]) x order by x::numeric loop
        kwh := v::numeric;
        return next;
      end loop;
    end if;
  end loop;
end $$;

-- ---------------------------------------------------------------------------------------------- key
-- The model segment is the canonical slug of the alias list when it names the model (buyer_interest_model_key).
create or replace function buyer_interest_product_key(facts jsonb)
 RETURNS text
 LANGUAGE sql
 STABLE
AS $function$
  with kwh as (
    select coalesce(buyer_interest_number(facts->'kwh'),
      case when facts->>'kwh_min' is not null and facts->>'kwh_min' = facts->>'kwh_max'
        then buyer_interest_number(facts->'kwh_min') end) as value
  ), part as (
    select 'part:' || buyer_interest_part(part) as key
    from jsonb_array_elements_text(coalesce(facts->'part_numbers', '[]'::jsonb)) part
    where buyer_interest_part(part) is not null
    order by 1 limit 1
  ), model_part as (
    select 'part:' || buyer_interest_part(buyer_interest_model_part_token(facts->>'model')) as key
    where buyer_interest_model_part_token(facts->>'model') is not null
      and buyer_interest_slug(facts->>'cell_maker') is null  -- a cell model (INR21700-50E) is not a part number
  ), wide as (
    select buyer_interest_model_wide_text(facts->>'make', facts->>'model') as model
  ), cellfmt as (
    select case when buyer_interest_format(facts->>'format') = 'cell'
      then buyer_interest_cell_format(facts->>'cell_format') end as value
  )
  select coalesce(
    (select key from part),
    (select key from model_part),
    case when buyer_interest_make(facts->>'make') is not null
        and buyer_interest_fold(buyer_interest_model_text(facts->>'model')) is not null
        and not buyer_interest_prose_model(facts->>'model')
        and (select value from kwh) is not null
      then 'model:' || buyer_interest_make(facts->>'make') || '-' || buyer_interest_model_key(facts->>'make', buyer_interest_model_text(facts->>'model')) || '-'
        || buyer_interest_kwh_text((select value from kwh)) || 'kwh' end,
    case when buyer_interest_slug(facts->>'cell_maker') is not null
        and buyer_interest_slug(facts->>'model') is not null
        and not buyer_interest_prose_model(facts->>'model')
      then 'cell:' || buyer_interest_slug(facts->>'cell_maker') || '-' || buyer_interest_slug(facts->>'model') end,
    case when buyer_interest_make(facts->>'make') is not null
        and buyer_interest_fold((select model from wide)) is not null
        and not buyer_interest_prose_model((select model from wide))
        and (select value from kwh) is null
      then 'model:' || buyer_interest_make(facts->>'make') || '-' || buyer_interest_model_key(facts->>'make', (select model from wide)) end,
    -- Broad is the last level. A stated make stays on the key, so two makes in one ask keep two lines. A cell with a
    -- stated cell format adds it (and its cell maker when no make is stated) before the chemistry.
    'broad:' || coalesce(buyer_interest_make(facts->>'make') || '-',
        case when (select value from cellfmt) is not null then buyer_interest_slug(facts->>'cell_maker') || '-' end, '')
      || coalesce((select value from cellfmt) || '-', '')
      || coalesce(buyer_interest_slug(buyer_interest_chemistry(facts->>'chemistry')), 'any') || '-'
      || case buyer_interest_format(facts->>'format')
           when 'pack' then 'packs' when 'module' then 'modules' when 'cell' then 'cells' when 'system' then 'systems'
           else 'batteries' end
  )
$function$;

-- ---------------------------------------------------------------------------------------------- fact sets
-- One fact set per line a row states. Without p_models this is 119's make x chemistry x format x cell format cross.
-- With p_models (the demand sync) a row that names models writes one set per named model and kWh, and a make-level set
-- only for each make that names no model. Either way, two or more makes or models with two or more chemistries are
-- not crossed: the sets carry no chemistry and chemistry_preference holds the list.
-- Capped at p_limit sets (60 when models are named); stated_total says how many the row really states.
drop function if exists buyer_interest_fact_sets(jsonb, jsonb, jsonb, int, text);
create or replace function buyer_interest_fact_sets(p_spec jsonb, p_context jsonb default '{}'::jsonb,
  p_fields jsonb default '{}'::jsonb, p_limit int default 12, p_title text default null, p_models boolean default false)
returns table (facts jsonb[], stated_total int) language plpgsql stable as $$
declare
  makes text[] := buyer_interest_make_list(buyer_interest_stated_list(p_spec->'makes', buyer_interest_first_text(p_spec->'make'),
    buyer_interest_first_text(p_context->'make'), buyer_interest_first_text(p_fields->'make')));
  chemists text[] := buyer_interest_stated_list(p_spec->'chemistries', buyer_interest_first_text(p_spec->'chemistry'),
    buyer_interest_first_text(p_context->'chemistry'), buyer_interest_first_text(p_fields->'chemistry'));
  formats text[] := buyer_interest_stated_list(p_spec->'formats', buyer_interest_first_text(p_spec->'format'),
    buyer_interest_first_text(p_context->'format'), buyer_interest_first_text(p_fields->'format'));
  cformats text[] := buyer_interest_cell_formats(p_spec, p_context, p_fields);
  entries text[] := '{}';
  entities jsonb[] := '{}';
  hit record;
  mk text;
  covered boolean;
  model_entities int := 0;
  entity_count int;
  preference text;
  sets jsonb[] := '{}';
  total int := 0;
  cap int := greatest(p_limit, 1);
  ent jsonb;
  c text;
  f text;
  cf text;
begin
  if makes = array[null]::text[] and buyer_interest_title_make(p_title) is not null then
    makes := array[buyer_interest_title_make(p_title)];
  end if;
  if formats = array[null]::text[] and buyer_interest_format(coalesce(buyer_interest_first_text(p_spec->'trade_kind'),
      buyer_interest_first_text(p_context->'trade_kind'))) is not null then
    formats := array[buyer_interest_format(coalesce(buyer_interest_first_text(p_spec->'trade_kind'),
      buyer_interest_first_text(p_context->'trade_kind')))];
  end if;

  -- The models the request names: its models list, or a model text that lists models (a separator).
  if p_models then
    if jsonb_typeof(p_spec->'models') = 'array' then
      select coalesce(array_agg(btrim(v)), '{}') into entries from jsonb_array_elements_text(p_spec->'models') v
       where nullif(btrim(v), '') is not null;
    end if;
    if cardinality(entries) = 0 and coalesce(p_spec->>'model', '') ~ '[,;/&]|\yand\y' then
      entries := array[btrim(p_spec->>'model')];
    end if;
    if cardinality(entries) > 0 then
      for hit in
        select distinct h.own, h.make_display, h.slug, h.name, h.kwh
          from unnest(entries) e, lateral buyer_interest_text_models(e, array_remove(makes, null)) h
         order by h.make_display, h.slug, h.kwh nulls first
      loop
        entities := entities || (jsonb_build_object('makes', jsonb_build_array(hit.make_display), 'make', hit.make_display,
          'model', hit.name, 'own', hit.own, 'slug', hit.slug)
          || case when hit.kwh is null then '{}'::jsonb
               else jsonb_build_object('kwh', hit.kwh, 'kwh_min', hit.kwh, 'kwh_max', hit.kwh) end);
      end loop;
    end if;
  end if;

  if cardinality(entities) > 0 then
    -- Makes the request names without any model keep their make-level set.
    select count(distinct e->>'own' || '/' || (e->>'slug')) into model_entities from unnest(entities) e;
    foreach mk in array array_remove(makes, null) loop
      -- "VW Group" is covered by a model of any make of the group.
      select exists (select 1 from unnest(entities) e, regexp_split_to_table(mk, '\s+or\s+', 'i') piece
                      where e->>'own' = buyer_interest_alias_make_fold(piece)
                         or (buyer_interest_make(piece) = 'vw-group'
                             and e->>'own' in ('volkswagen', 'audi', 'skoda', 'seat', 'cupra', 'porsche'))) into covered;
      if not covered then
        -- A make-level set states no model: the request's model list text must not ride along as its model.
        entities := entities || jsonb_build_object('makes', jsonb_build_array(mk), 'make', mk, 'no_model', true);
      end if;
    end loop;
    -- A model line per kWh still counts as the one model it is.
    entity_count := model_entities + (select count(*) from unnest(entities) e where not (e ? 'slug'));
    cap := greatest(p_limit, 60);
  else
    foreach mk in array makes loop
      entities := entities || jsonb_build_object('makes', case when mk is null then '[]'::jsonb else jsonb_build_array(mk) end,
        'make', mk);
    end loop;
    entity_count := cardinality(array_remove(makes, null));
  end if;

  -- Chemistries are a preference, not a pairing, when several makes or models state several of them.
  if cardinality(array_remove(chemists, null)) >= 2 and entity_count >= 2 then
    preference := array_to_string(array_remove(chemists, null), ' / ');
    chemists := array[null]::text[];
  end if;

  for ent, c, f, cf in
    select e.value, y.value, z.value, w.value
    from unnest(entities) with ordinality e(value, ord)
    cross join unnest(chemists) y(value)
    cross join unnest(formats) z(value)
    cross join unnest(cformats) w(value)
    order by e.ord, 2 nulls first, 3 nulls first, 4 nulls first
  loop
    total := total + 1;
    continue when total > cap;
    sets := sets || (buyer_interest_facts(
      case when ent ? 'no_model' then p_spec - 'model' - 'models' else p_spec end || (ent - 'own' - 'slug' - 'no_model') || jsonb_build_object(
        'chemistries', case when c is null then '[]'::jsonb else jsonb_build_array(c) end, 'chemistry', c,
        'formats', case when f is null then '[]'::jsonb else jsonb_build_array(f) end, 'format', f),
      case when ent ? 'no_model' then p_context - 'model' else p_context end, p_fields - case when ent ? 'no_model' then 'model' else '' end)
      || case when cf is null then '{}'::jsonb else jsonb_build_object('cell_format', cf) end
      || case when preference is null then '{}'::jsonb else jsonb_build_object('chemistry_preference', preference) end);
  end loop;
  stated_total := total;
  facts := sets;
  return next;
end $$;

-- ---------------------------------------------------------------------------------------------- sync
create or replace function buyer_interest_sync_demand_row(p_id text)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
declare
  row_ crm_bulk_listings%rowtype;
  fact_sets jsonb[];
  product_sets jsonb[];
  set_keys text[];
  stated_total int;
  facts jsonb;
  set_key text;
  i int;
  keys text[] := '{}';
  line_kind text;
  line_reason text;
  first_d date;
  last_d date;
  qty numeric;
  unit text;
  price_v numeric;
  currency_v text;
  price_unit_v text;
  price_basis_v text;
  needed date;
  expiry date;
  expiry_sticky boolean := false;
  said boolean := false;
  refs text[];
begin
  -- One writer per source: the trigger and the backfill queue here, and each reads the row after the lock is
  -- granted, so the last one in always writes the newest facts. FOR KEY SHARE re-reads the current row version
  -- without blocking an ordinary UPDATE, so a writer holding the row cannot deadlock with a sync waiting here.
  perform pg_advisory_xact_lock(hashtext('demand:' || p_id));
  select * into row_ from crm_bulk_listings where id = p_id and kind = 'demand' for key share;
  if row_.id is null then
    -- Deleted, or no longer a demand row: its lines no longer describe a buyer's wish.
    delete from buyer_interest where demand_id = p_id;
    return;
  end if;

  -- A buyer we cannot name a company for cannot hold a line; the api resolves the company on write.
  if row_.company_id is null then
    delete from buyer_interest where demand_id = row_.id;
    return;
  end if;

  first_d := coalesce(row_.observed_on, row_.created_at::date, current_date);
  last_d := greatest(coalesce(buyer_interest_first_text(row_.spec->'confirmed_on')::date, first_d), first_d);

  qty := buyer_interest_number(row_.spec->'volume');
  unit := nullif(btrim(coalesce(row_.spec->>'volume_unit', '')), '');
  price_v := buyer_interest_number(row_.spec->'max_price');
  currency_v := nullif(btrim(coalesce(row_.spec->>'price_currency', '')), '');
  price_unit_v := nullif(btrim(coalesce(row_.spec->>'price_unit', '')), '');
  price_basis_v := case when price_v is null then null else 'target' end;
  needed := case when coalesce(row_.spec->>'needed_by', '') ~ '^\d{4}-\d{2}-\d{2}$'
    then (row_.spec->>'needed_by')::date end;
  refs := array_remove(array[row_.source_id, 'crm:' || row_.id]::text[], null);

  if row_.status in ('open', 'qualifying') then
    line_kind := 'ask';
    expiry := needed;
  elsif row_.status = 'closed' and row_.closed_reason = 'expired' then
    -- An expired ask stays visible as history with its expiry; the stale-line delete below drops an older
    -- bought/declined outcome, so a re-staged ask never keeps a superseded decision.
    line_kind := 'ask';
    expiry := coalesce(needed, current_date);
    expiry_sticky := true;  -- the day it lapsed, not the day a later edit touched the row
  elsif row_.status = 'closed' and row_.closed_reason in ('bought_elsewhere', 'no_longer_needed') then
    -- A request that ended without us is not a decline of a product: it writes no Want. Its non-mastered line (an
    -- older ask or outcome) goes, as for any other closure.
    delete from buyer_interest where demand_id = row_.id and ownership <> 'mastered';
    return;
  elsif row_.status = 'closed' and row_.closed_reason = 'bought_from_us' then
    line_kind := 'bought';
    expiry := null;
  elsif row_.status = 'closed' and row_.closed_reason in ('not_a_fit', 'offer_reply') then
    -- The request was not a fit for the marketplace, or it is a buyer's reply to our offer: either way the buyer
    -- said they want this product. That is a 'Said' (interest) line, dated when it was seen, for 180 days. Interest is
    -- a mastered kind, so it merges with the buyer's existing line for the same product instead of duplicating it.
    line_kind := 'interest';
    said := true;
    expiry := first_d + 180;
  else
    -- Not a buying fact (duplicate, moved to profile, converted to supply/trade, research row): drop the asks.
    delete from buyer_interest where demand_id = row_.id;
    return;
  end if;

  select fs.facts, fs.stated_total into fact_sets, stated_total
  from buyer_interest_fact_sets(row_.spec, row_.context, '{}'::jsonb, 12, null, true) fs;

  -- p_models: a request that names several models writes a line per model (and per kWh); see buyer_interest_fact_sets.
  -- A row that states no product at all is not a want: it is not written, only recorded for a person to fix.
  select coalesce(array_agg(fact), '{}'), coalesce(array_agg(buyer_interest_product_key(fact)), '{}')
    into product_sets, set_keys from unnest(fact_sets) fact
   where buyer_interest_states_product(fact);
  delete from buyer_interest_sync_errors where operation = 'no_product_facts' and source_id = row_.id;
  if cardinality(product_sets) = 0 then
    delete from buyer_interest where demand_id = row_.id;
    insert into buyer_interest_sync_errors (source_table, source_id, operation, message)
    values ('crm_bulk_listings', row_.id, 'no_product_facts',
      format('states no product fact (make, chemistry, format, part or kWh): %s',
        left(coalesce(nullif(btrim(coalesce(row_.summary, '')), ''), row_.source_id, row_.id), 120)));
    return;
  end if;

  -- The key set this row states now. Anything else on this source is stale: an old chemistry, a dropped make,
  -- or an outcome the row has since superseded.
  select coalesce(array_agg(distinct k), '{}') into keys from unnest(set_keys) k;

  delete from buyer_interest
  where demand_id = row_.id and not (kind = line_kind and product_key = any(keys));

  for i in 1..cardinality(product_sets) loop
    facts := product_sets[i];
    set_key := set_keys[i];
    if exists (select 1 from buyer_interest_suppressed s where s.company_id = row_.company_id and s.kind = line_kind
        and s.product_key = set_key) then
      continue;  -- removed in a cleanup: a re-sync does not bring the line back
    end if;
    if said then
      insert into buyer_interest (id, company_id, person_id, kind, ownership, product_key, product_key_level,
        make, model, raw_product, format, chemistry, kwh_min, kwh_max, first_seen, last_seen, quantity, quantity_unit,
        quantity_basis, price, price_currency, price_unit, price_basis, source_refs, expires_on, demand_id)
      values ('bi_' || replace(gen_random_uuid()::text, '-', ''), row_.company_id, row_.person_id, 'interest', 'mastered',
        set_key, buyer_interest_key_level(set_key),
        facts->>'make', facts->>'model', buyer_interest_raw_product(facts),
        buyer_interest_format(facts->>'format'),
        buyer_interest_chemistry(facts->>'chemistry'), buyer_interest_number(facts->'kwh_min'),
        buyer_interest_number(facts->'kwh_max'), first_d, last_d, qty, unit,
        case when qty is null then 'not_stated' else 'stated' end,
        price_v, currency_v, price_unit_v, price_basis_v, refs, expiry, row_.id)
      on conflict (company_id, product_key, kind) where ownership = 'mastered' do update set
        person_id = coalesce(excluded.person_id, buyer_interest.person_id),
        first_seen = least(buyer_interest.first_seen, excluded.first_seen),
        last_seen = greatest(buyer_interest.last_seen, excluded.last_seen),
        expires_on = case when buyer_interest.expires_on is null then null
          else greatest(buyer_interest.expires_on, excluded.expires_on) end,
        source_refs = (select array_agg(distinct ref order by ref) from unnest(buyer_interest.source_refs || excluded.source_refs) ref),
        updated_at = now();
      continue;
    end if;
    insert into buyer_interest (id, company_id, person_id, kind, ownership, product_key, product_key_level,
      make, model, raw_product, format, chemistry, kwh_min, kwh_max, first_seen, last_seen, quantity, quantity_unit,
      quantity_basis, price, price_currency, price_unit, price_basis, source_refs, expires_on, demand_id,
      decline_reason)
    values ('bi_' || replace(gen_random_uuid()::text, '-', ''), row_.company_id, row_.person_id, line_kind, 'synced',
      set_key, buyer_interest_key_level(set_key),
      facts->>'make', facts->>'model', buyer_interest_raw_product(facts),
      buyer_interest_format(facts->>'format'),
      buyer_interest_chemistry(facts->>'chemistry'), buyer_interest_number(facts->'kwh_min'),
      buyer_interest_number(facts->'kwh_max'), first_d, last_d, qty, unit,
      case when qty is null then 'not_stated' else 'stated' end,
      price_v, currency_v, price_unit_v, price_basis_v, refs, expiry, row_.id, line_reason)
    on conflict (kind, demand_id, product_key) where demand_id is not null do update set
      company_id = excluded.company_id,
      person_id = coalesce(excluded.person_id, buyer_interest.person_id),
      product_key_level = excluded.product_key_level,
      make = coalesce(excluded.make, buyer_interest.make),
      model = coalesce(excluded.model, buyer_interest.model),
      raw_product = coalesce(excluded.raw_product, buyer_interest.raw_product),
      format = coalesce(excluded.format, buyer_interest.format),
      chemistry = coalesce(excluded.chemistry, buyer_interest.chemistry),
      kwh_min = coalesce(excluded.kwh_min, buyer_interest.kwh_min),
      kwh_max = coalesce(excluded.kwh_max, buyer_interest.kwh_max),
      first_seen = least(buyer_interest.first_seen, excluded.first_seen),
      last_seen = greatest(buyer_interest.last_seen, excluded.last_seen),
      quantity = coalesce(excluded.quantity, buyer_interest.quantity),
      quantity_unit = coalesce(excluded.quantity_unit, buyer_interest.quantity_unit),
      quantity_basis = coalesce(excluded.quantity_basis, buyer_interest.quantity_basis),
      price = coalesce(excluded.price, buyer_interest.price),
      price_currency = coalesce(excluded.price_currency, buyer_interest.price_currency),
      price_unit = coalesce(excluded.price_unit, buyer_interest.price_unit),
      price_basis = coalesce(excluded.price_basis, buyer_interest.price_basis),
      source_refs = (select array_agg(distinct ref order by ref) from unnest(buyer_interest.source_refs || excluded.source_refs) ref),
      expires_on = case when expiry_sticky then coalesce(buyer_interest.expires_on, excluded.expires_on)
        else excluded.expires_on end,
      decline_reason = coalesce(excluded.decline_reason, buyer_interest.decline_reason),
      updated_at = now();
  end loop;

  if stated_total > cardinality(product_sets) then
    insert into buyer_interest_sync_errors (source_table, source_id, operation, message)
    values ('crm_bulk_listings', row_.id, 'truncated',
      format('kept %s of %s stated combinations', cardinality(product_sets), stated_total));
  end if;
end $function$;

commit;
