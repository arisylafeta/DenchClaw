-- One listings table for both sides of the market: demand (a buyer wants) and supply (a seller offers).
-- Same columns for both; kind-specific values live in spec jsonb (merged with each old table's existing spec).
-- Adds crm_trade_listings, crm_trade_listing_activity and crm_trade_matches and backfills them from
-- crm_bulk_trade_demand / _supply / _demand_activity / _demand_matches / _supply_matches.
-- Existing ids are kept, so ?demand=<id> and ?supply=<id> links keep working. Old tables are untouched
-- (dropped in a later migration after verification). Idempotent: safe to re-run before cutover to pick up late writes.
-- Apply only after a current backup and explicit schema approval.
begin;

create table if not exists crm_trade_listings (
  id text primary key,
  kind text not null check (kind in ('demand', 'supply')),
  party text not null check (length(btrim(party)) > 0),            -- buyer / seller name as written
  company_id text references crm_companies(id) on delete set null,
  person_id text references crm_people(id) on delete set null,
  contact text,
  email text check (email is null or email = lower(email)),
  summary text not null check (length(btrim(summary)) > 0),        -- what is wanted / offered
  quantity text,
  location text,
  note text,
  status text not null check (status in ('open', 'qualifying', 'closed')),
  closed_reason text check (closed_reason in (
    'bought_from_us', 'bought_elsewhere', 'no_longer_needed', 'expired', 'other', 'duplicate', 'moved_to_profile',
    'moved_to_lot', 'offer_reply', 'research_profile', 'recycling', 'supply', 'not_demand',
    'sold', 'became_trade', 'gone', 'not_a_fit')),
  observed_on date,
  source_kind text check (source_kind in ('research', 'survey', 'email', 'call', 'auction', 'manual', 'import', 'whatsapp')),
  source_id text,
  source_thread text,
  source_label text,
  source_url text,
  source_quote text,
  match_hash text,
  spec jsonb not null default '{}'::jsonb check (jsonb_typeof(spec) = 'object'),     -- kind-specific values
  context jsonb not null default '{}'::jsonb check (jsonb_typeof(context) = 'object'), -- editorial: listing_title, application, ...
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((status = 'closed') = (closed_reason is not null))
);
create unique index if not exists crm_trade_listings_source_idx on crm_trade_listings (kind, source_kind, source_id) where source_id is not null;
create index if not exists crm_trade_listings_open_idx on crm_trade_listings (kind, observed_on desc) where status = 'open';
create index if not exists crm_trade_listings_company_idx on crm_trade_listings (company_id) where company_id is not null;
create index if not exists crm_trade_listings_person_idx on crm_trade_listings (person_id) where person_id is not null;
create index if not exists crm_trade_listings_email_idx on crm_trade_listings (email) where email is not null;
create index if not exists crm_trade_listings_thread_idx on crm_trade_listings (source_thread) where source_thread is not null and status = 'open';

create table if not exists crm_trade_listing_activity (
  id bigint generated by default as identity primary key,
  listing_id text not null references crm_trade_listings(id) on delete cascade,
  person_id text references crm_people(id) on delete set null,   -- who this touch was with, when it is a person
  kind text not null check (kind in ('note', 'research', 'outreach', 'call', 'quote', 'supply', 'status', 'document', 'mail', 'whatsapp')),
  title text not null check (length(btrim(title)) > 0),
  body text,
  ref_kind text check (ref_kind in ('lot', 'supply', 'stock', 'email', 'person', 'company', 'url')),
  ref_id text,
  data jsonb not null default '{}'::jsonb,
  actor_user_id uuid references crm_users(id) on delete set null,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists crm_trade_listing_activity_time on crm_trade_listing_activity (listing_id, occurred_at desc);
create index if not exists crm_trade_listing_activity_person on crm_trade_listing_activity (person_id) where person_id is not null;

-- A demand listing matched to something that could serve it: a supply listing or a trade (lot).
create table if not exists crm_trade_matches (
  demand_id text not null references crm_trade_listings(id) on delete cascade,
  target_kind text not null check (target_kind in ('supply', 'trade')),
  target_id text not null,
  strength text not null check (strength in ('strong', 'partial')),
  reason text not null,
  hidden boolean not null default false,
  matched_at timestamptz not null default now(),
  primary key (demand_id, target_kind, target_id)
);
create index if not exists crm_trade_matches_target on crm_trade_matches (target_kind, target_id);

-- Backfill: demand. Old typed columns become spec keys; null values are omitted.
insert into crm_trade_listings (id, kind, party, company_id, person_id, contact, email, summary, quantity, location, note,
  status, closed_reason, observed_on, source_kind, source_id, source_thread, source_label, source_url, source_quote,
  match_hash, spec, context, created_at, updated_at)
select d.id, 'demand', d.buyer, d.company_id, d.person_id, d.contact, d.email, d.wants, d.quantity, d.location, d.note,
  d.status, d.closed_reason, d.observed_on, d.source_kind, d.source_id, d.source_thread, d.source_label, d.source_url, d.source_quote,
  d.match_hash,
  coalesce(d.spec, '{}'::jsonb) || jsonb_strip_nulls(jsonb_build_object(
    'intent', d.kind, 'basis', d.basis, 'needed_by', d.needed_by, 'volume', d.volume, 'volume_unit', d.volume_unit,
    'max_price', d.max_price, 'price_currency', d.price_currency, 'price_unit', d.price_unit, 'price_basis', d.price_basis,
    'fee_eur', d.fee_eur, 'reputation', d.reputation, 'qualify_question', d.qualify_question,
    'qualify_asked_on', d.qualify_asked_on, 'qualify_entered_on', d.qualify_entered_on, 'product_family', d.product_family,
    'confirmed_on', d.confirmed_on, 'supply_match_hash', d.supply_match_hash,
    'priority', case when d.priority then true end)),
  coalesce(d.context, '{}'::jsonb), d.created_at, d.updated_at
from crm_bulk_trade_demand d
on conflict (id) do update set
  party = excluded.party, company_id = excluded.company_id, person_id = excluded.person_id, contact = excluded.contact,
  email = excluded.email, summary = excluded.summary, quantity = excluded.quantity, location = excluded.location,
  note = excluded.note, status = excluded.status, closed_reason = excluded.closed_reason, observed_on = excluded.observed_on,
  source_kind = excluded.source_kind, source_id = excluded.source_id, source_thread = excluded.source_thread,
  source_label = excluded.source_label, source_url = excluded.source_url, source_quote = excluded.source_quote,
  match_hash = excluded.match_hash, spec = excluded.spec, context = excluded.context, updated_at = excluded.updated_at;

-- Backfill: supply.
insert into crm_trade_listings (id, kind, party, company_id, person_id, contact, email, summary, quantity, location,
  status, closed_reason, observed_on, source_kind, source_id, source_thread, source_label, source_url, source_quote,
  match_hash, spec, created_at, updated_at)
select s.id, 'supply', s.seller, s.company_id, s.person_id, s.contact, s.email, s.offers, s.quantity, s.location,
  s.status, s.closed_reason, s.observed_on, s.source_kind, s.source_id, s.source_thread, s.source_label, s.source_url, s.source_quote,
  s.match_hash,
  jsonb_strip_nulls(jsonb_build_object('trade_kind', s.trade_kind, 'est_tonnes', s.est_tonnes, 'size_note', s.size_note)),
  s.created_at, s.updated_at
from crm_bulk_trade_supply s
on conflict (id) do update set
  party = excluded.party, company_id = excluded.company_id, person_id = excluded.person_id, contact = excluded.contact,
  email = excluded.email, summary = excluded.summary, quantity = excluded.quantity, location = excluded.location,
  status = excluded.status, closed_reason = excluded.closed_reason, observed_on = excluded.observed_on,
  source_kind = excluded.source_kind, source_id = excluded.source_id, source_thread = excluded.source_thread,
  source_label = excluded.source_label, source_url = excluded.source_url, source_quote = excluded.source_quote,
  match_hash = excluded.match_hash, spec = excluded.spec, updated_at = excluded.updated_at;

-- Backfill: activity (ids kept; the new rows are added once, by id).
insert into crm_trade_listing_activity (id, listing_id, kind, title, body, ref_kind, ref_id, data, actor_user_id, occurred_at, created_at)
overriding system value
select a.id, a.demand_id, a.kind, a.title, a.body, a.ref_kind, a.ref_id, a.data, a.actor_user_id, a.occurred_at, a.created_at
from crm_bulk_trade_demand_activity a
on conflict (id) do nothing;
select setval(pg_get_serial_sequence('crm_trade_listing_activity', 'id'), greatest((select max(id) from crm_trade_listing_activity), 1));

-- Backfill: matches. Demand -> trade (old demand_matches; buyer_id was never filled) and demand -> supply (old supply_matches).
insert into crm_trade_matches (demand_id, target_kind, target_id, strength, reason, hidden, matched_at)
select demand_id, 'trade', lot_id, strength, reason, hidden, matched_at from crm_bulk_trade_demand_matches
on conflict do nothing;
insert into crm_trade_matches (demand_id, target_kind, target_id, strength, reason, hidden, matched_at)
select demand_id, 'supply', supply_id, strength, reason, hidden, matched_at from crm_bulk_trade_supply_matches
on conflict do nothing;

-- Triggers (created after the backfill so it does not write status activity). Both kinds share them;
-- the qualification clock only applies to demand and keeps its dates in spec.
create or replace function trade_listing_qualification_clock() returns trigger language plpgsql as $$
declare today text := ((now() at time zone 'Europe/London')::date)::text;
begin
  if new.kind = 'demand' and new.status = 'qualifying' then
    if TG_OP = 'INSERT' then
      if new.spec->>'qualify_entered_on' is null then new.spec := new.spec || jsonb_build_object('qualify_entered_on', today); end if;
    elsif old.status is distinct from new.status then
      new.spec := (new.spec - 'qualify_asked_on') || jsonb_build_object('qualify_entered_on', today);
    end if;
  end if;
  return new;
end $$;

create or replace function trade_listing_status_activity() returns trigger language plpgsql as $$
begin
  if TG_OP = 'INSERT' then
    insert into crm_trade_listing_activity (listing_id, kind, title, data)
    values (new.id, 'status', initcap(new.status), jsonb_build_object('status', new.status));
  elsif old.status is distinct from new.status then
    insert into crm_trade_listing_activity (listing_id, kind, title, data)
    values (new.id, 'status', case when new.status = 'closed' then 'Closed · ' || coalesce(new.closed_reason, 'closed')
      when new.status = 'open' then 'Opened' else 'Qualifying' end,
      jsonb_build_object('from', old.status, 'status', new.status, 'reason', new.closed_reason));
  elsif new.status = 'closed' and old.closed_reason is distinct from new.closed_reason then
    insert into crm_trade_listing_activity (listing_id, kind, title, data)
    values (new.id, 'status', 'Category · ' || new.closed_reason,
      jsonb_build_object('from_reason', old.closed_reason, 'reason', new.closed_reason, 'status', new.status));
  end if;
  return new;
end $$;

drop trigger if exists trade_listing_qualification_clock on crm_trade_listings;
create trigger trade_listing_qualification_clock before insert or update on crm_trade_listings
  for each row execute function trade_listing_qualification_clock();
drop trigger if exists trade_listing_status_activity on crm_trade_listings;
create trigger trade_listing_status_activity after insert or update on crm_trade_listings
  for each row execute function trade_listing_status_activity();

commit;
