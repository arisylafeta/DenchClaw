-- Registry of bulk listing attributes, kept in the database instead of JSON files in the repo.
-- Seeded from the former apps/web/lib/bulk-trade-templates.json (trade fields per kind, required files) and
-- apps/web/lib/buy-box-spec.json (buyer ask lists, numbers, units, currencies). Content is identical to those files.
--   crm_bulk_attributes       one row per attribute. side 'listing' = a fact about a supply/trade listing (what
--                             crm_bulk_listing_fields stores); side 'demand' = a criterion in a demand listing's spec.
--   crm_bulk_attribute_kinds  which trade kinds show a listing attribute, with that kind's label and order.
--   crm_bulk_attribute_options allowed values of a set/enum attribute (chemistries, makes, units, currencies ...).
--   crm_bulk_required_files   files every trade needs and the step each unlocks.
-- Apply only after a current backup and explicit schema approval.
begin;

create table if not exists crm_bulk_attributes (
  key text primary key,
  side text not null check (side in ('listing', 'demand')),
  label text not null,
  type text not null default 'text' check (type in ('text', 'number', 'date', 'set', 'enum')),
  unit text,
  needed_for text check (needed_for in ('Teaser', 'Bids', 'Shipping', 'Closing')),
  visibility text check (visibility in ('teaser', 'after_nda', 'after_loi', 'never')),
  min numeric,
  max numeric,
  group_name text,
  sort_order integer not null default 0
);
create table if not exists crm_bulk_attribute_kinds (
  attribute_key text not null references crm_bulk_attributes(key) on delete cascade,
  kind text not null check (kind in ('packs', 'cells', 'systems', 'recycling')),
  label text not null,
  sort_order integer not null,
  primary key (attribute_key, kind)
);
create table if not exists crm_bulk_attribute_options (
  attribute_key text not null references crm_bulk_attributes(key) on delete cascade,
  value text not null,
  sort_order integer not null,
  primary key (attribute_key, value)
);
create table if not exists crm_bulk_required_files (
  file_type text primary key,
  label text not null,
  needed_for text not null check (needed_for in ('Teaser', 'Bids', 'Shipping', 'Closing')),
  sort_order integer not null
);

